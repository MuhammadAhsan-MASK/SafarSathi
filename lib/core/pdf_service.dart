import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

class PDFService {
  /// Sanitizes text so PDF standard fonts render cleanly without missing-glyph boxes.
  static String _pdfSafe(String text) {
    return text
        .replaceAll('➔', '->')
        .replaceAll('→', '->')
        .replaceAll('•', '-')
        .replaceAll('–', '-')
        .replaceAll('—', '-')
        .replaceAll(RegExp(r'[^\x00-\x7F]'), '')
        .trim();
  }

  static Future<void> generateItineraryPDF({
    required String destination,
    String? origin,
    List<Map<String, dynamic>> activities = const [],
    List<Map<String, dynamic>>? daySections,
    Map<String, String>? budgetSummary,
  }) async {
    final pdf = pw.Document();

    final List<Map<String, dynamic>> effectiveSections = daySections ??
        [
          {
            'dayTitle': 'Planned Itinerary',
            'budget': '',
            'activities': activities,
          },
        ];

    final safeDest = _pdfSafe(destination);
    final safeOrigin = origin != null && origin.isNotEmpty ? _pdfSafe(origin) : '';

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(28),
        build: (pw.Context context) {
          final List<pw.Widget> widgets = [
            // Top Header Banner
            pw.Container(
              padding: const pw.EdgeInsets.all(16),
              decoration: pw.BoxDecoration(
                color: PdfColors.deepPurple800,
                borderRadius: const pw.BorderRadius.all(pw.Radius.circular(10)),
              ),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text(
                    safeOrigin.isNotEmpty
                        ? 'Trip Itinerary: $safeOrigin -> $safeDest'
                        : 'Trip Itinerary: $safeDest',
                    style: pw.TextStyle(
                      fontSize: 20,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColors.white,
                    ),
                  ),
                  pw.SizedBox(height: 6),
                  pw.Text(
                    'Exported Days: ${effectiveSections.length} day(s) | Generated by SafarSathi',
                    style: const pw.TextStyle(
                      fontSize: 11,
                      color: PdfColors.grey200,
                    ),
                  ),
                ],
              ),
            ),
            pw.SizedBox(height: 14),
          ];

          if (budgetSummary != null && budgetSummary.isNotEmpty) {
            final gross = _pdfSafe(budgetSummary['grossBudget'] ?? '');
            final transport = _pdfSafe(budgetSummary['transportCost'] ?? '');
            final stay = _pdfSafe(budgetSummary['stayCost'] ?? '');
            final net = _pdfSafe(budgetSummary['netDailyBudget'] ?? '');

            widgets.add(
              pw.Container(
                margin: const pw.EdgeInsets.only(bottom: 14),
                padding: const pw.EdgeInsets.all(12),
                decoration: pw.BoxDecoration(
                  color: PdfColors.grey100,
                  border: pw.Border.all(color: PdfColors.grey300),
                  borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
                ),
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      'Trip Budget Breakdown (After Transport & Stay)',
                      style: pw.TextStyle(
                        fontSize: 12,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColors.deepPurple900,
                      ),
                    ),
                    pw.SizedBox(height: 6),
                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                      children: [
                        pw.Text('Total Trip Budget:', style: const pw.TextStyle(fontSize: 10.5)),
                        pw.Text(gross, style: pw.TextStyle(fontSize: 10.5, fontWeight: pw.FontWeight.bold)),
                      ],
                    ),
                    pw.SizedBox(height: 3),
                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                      children: [
                        pw.Text('Less Transport Cost:', style: const pw.TextStyle(fontSize: 10.5, color: PdfColors.red800)),
                        pw.Text('- $transport', style: const pw.TextStyle(fontSize: 10.5, color: PdfColors.red800)),
                      ],
                    ),
                    pw.SizedBox(height: 3),
                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                      children: [
                        pw.Text('Less Hotel / Stay Cost:', style: const pw.TextStyle(fontSize: 10.5, color: PdfColors.red800)),
                        pw.Text('- $stay', style: const pw.TextStyle(fontSize: 10.5, color: PdfColors.red800)),
                      ],
                    ),
                    pw.Divider(color: PdfColors.grey400),
                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                      children: [
                        pw.Text(
                          'Net Remaining for Daily Itinerary (Food & Activities):',
                          style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold, color: PdfColors.green900),
                        ),
                        pw.Text(
                          net,
                          style: pw.TextStyle(fontSize: 11.5, fontWeight: pw.FontWeight.bold, color: PdfColors.green900),
                        ),
                      ],
                    ),
                  ],
                ),
              ),
            );
          }

          for (final section in effectiveSections) {
            final dayTitle = _pdfSafe((section['dayTitle'] ?? 'Day').toString());
            final dayBudget = _pdfSafe((section['budget'] ?? '').toString());
            final dayActivities = List<Map<String, dynamic>>.from(section['activities'] ?? []);

            double dayActivityTotal = 0;
            for (final a in dayActivities) {
              dayActivityTotal += ((a['cost'] ?? 0) as num).toDouble();
            }

            // Day Header Strip
            widgets.add(
              pw.Container(
                margin: const pw.EdgeInsets.only(bottom: 10, top: 6),
                padding: const pw.EdgeInsets.symmetric(horizontal: 12, vertical: 8),
                decoration: pw.BoxDecoration(
                  color: PdfColors.deepPurple50,
                  border: pw.Border.all(color: PdfColors.deepPurple200),
                  borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
                ),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text(
                      dayTitle,
                      style: pw.TextStyle(
                        fontSize: 14,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColors.deepPurple900,
                      ),
                    ),
                    if (dayBudget.isNotEmpty)
                      pw.Text(
                        'Net Day Budget: $dayBudget',
                        style: pw.TextStyle(
                          fontSize: 11,
                          fontWeight: pw.FontWeight.bold,
                          color: PdfColors.green800,
                        ),
                      ),
                  ],
                ),
              ),
            );

            for (final activity in dayActivities) {
              final title = _pdfSafe((activity['title'] ?? '').toString());
              final time = _pdfSafe((activity['time'] ?? '').toString());
              final period = _pdfSafe((activity['period'] ?? '').toString());
              final desc = _pdfSafe((activity['desc'] ?? '').toString());
              final costNum = ((activity['cost'] ?? 0) as num).toDouble();
              final costLabel = costNum <= 0 ? 'FREE' : 'PKR ${costNum.toStringAsFixed(0)}';

              widgets.add(
                pw.Container(
                  margin: const pw.EdgeInsets.only(bottom: 10),
                  padding: const pw.EdgeInsets.all(10),
                  decoration: pw.BoxDecoration(
                    border: pw.Border.all(color: PdfColors.grey300),
                    borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
                  ),
                  child: pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Row(
                        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                        children: [
                          pw.Expanded(
                            child: pw.Text(
                              title,
                              style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 13),
                            ),
                          ),
                          pw.SizedBox(width: 8),
                          pw.Text(
                            period.isNotEmpty ? '$period | $time' : time,
                            style: const pw.TextStyle(color: PdfColors.grey700, fontSize: 10),
                          ),
                        ],
                      ),
                      if (desc.isNotEmpty) ...[
                        pw.SizedBox(height: 4),
                        pw.Text(desc, style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey800)),
                      ],
                      pw.SizedBox(height: 5),
                      pw.Text(
                        'Estimated Cost: $costLabel',
                        style: pw.TextStyle(
                          fontSize: 10.5,
                          fontWeight: pw.FontWeight.bold,
                          color: costNum <= 0 ? PdfColors.teal700 : PdfColors.green800,
                        ),
                      ),
                    ],
                  ),
                ),
              );
            }

            widgets.add(
              pw.Align(
                alignment: pw.Alignment.centerRight,
                child: pw.Padding(
                  padding: const pw.EdgeInsets.only(bottom: 14),
                  child: pw.Text(
                    'Day Activity Subtotal: PKR ${dayActivityTotal.toStringAsFixed(0)}',
                    style: pw.TextStyle(
                      fontSize: 11,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColors.deepPurple800,
                    ),
                  ),
                ),
              ),
            );
          }

          return widgets;
        },
      ),
    );

    final safeFilename = safeDest.replaceAll(RegExp(r'[^a-zA-Z0-9_-]'), '_').toLowerCase();
    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
      name: 'itinerary_$safeFilename.pdf',
    );
  }
}
